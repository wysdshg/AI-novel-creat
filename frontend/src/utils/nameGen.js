// 生成 count 个指定类型/风格的候选名字，批次内去重。
// fixedSurname / lenMode 仅在 type === '角色' 时生效。
export function genNames(type, count = 8, style = '雅致', fixedSurname = '', lenMode = 'random') {
  const fn = GEN[type]
  if (!fn) return []
  const out = new Set()
  let guard = 0
  const limit = count * 40
  while (out.size < count && guard < limit) {
    out.add(fn(style, fixedSurname, lenMode))
    guard++
  }
  return [...out]
}
