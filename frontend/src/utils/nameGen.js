const pick = (arr) => arr[Math.floor(Math.random() * arr.length)]

// 加权随机：items = [[value, weight], ...]
const wPick = (items) => {
  const total = items.reduce((s, [, w]) => s + w, 0)
  let r = Math.random() * total
  for (const [v, w] of items) {
    r -= w
    if (r <= 0) return v
  }
  return items[items.length - 1][0]
}

