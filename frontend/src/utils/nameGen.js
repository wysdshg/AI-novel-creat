function genCharacter(style, fixedSurname = '', lenMode = 'random') {
  const sur = (fixedSurname && fixedSurname.trim()) || randomSurname()
  // 市井风格几乎全是二字百姓名；其它风格也以二字为主
  const twoProb = style === '市井' ? 0.95 : 0.8
  // lenMode 仅对角色生效：random（按比例）/ single（单字）/ double（二字）/ triple（三字）
  let isSingle, isDouble, isTriple
  if (lenMode === 'single') {
    isSingle = true; isDouble = false; isTriple = false
  } else if (lenMode === 'double') {
    isSingle = false; isDouble = true; isTriple = false
  } else if (lenMode === 'triple') {
    isSingle = false; isDouble = false; isTriple = true
  } else {
    isSingle = Math.random() >= twoProb; isDouble = !isSingle; isTriple = false
  }
  let given = ''
  if (isTriple) {
    // 三字名：姓 + 二字（多从百姓俗名/风格成对词取），复姓时为四字亦接受
    given = pick(GIVEN_PAIRS[style] || GIVEN_PAIRS.雅致)
  } else if (isDouble) {
    if (style === '市井') {
      given = Math.random() < 0.9 ? pick(GIVEN_PAIRS.市井) : pick(GIVEN_PAIRS.江湖)
    } else {
      given = Math.random() < 0.5 ? pick(GIVEN_PAIRS.市井) : pick(GIVEN_PAIRS[style] || GIVEN_PAIRS.雅致)
    }
  } else {
    given = pick(GIVEN_SINGLE[style] || GIVEN_SINGLE.雅致)
  }
  return sur + given
}

