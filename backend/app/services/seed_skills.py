def install(db: Session, overwrite: bool = False) -> dict:
    """安装预置 SKILL。幂等：同名已存在时默认跳过，不覆盖作者的修改。

    overwrite=True 时重置为出厂内容（作者改崩了想还原时用）。
    """
    now = datetime.now(timezone.utc)
    created, updated, skipped = [], [], []

    for seed in SEEDS:
        existing = db.query(CustomSkillORM).filter_by(name=seed["name"]).first()
        if existing is not None:
            if not overwrite:
                skipped.append(seed["name"])
                continue
            existing.prompt_body = seed["prompt_body"]
            existing.trigger = seed["trigger"]
            existing.category = seed["category"]
            existing.priority = seed["priority"]
            existing.tags = seed["tags"]
            existing.description = seed["description"]
            existing.builtin = True
            existing.updated_at = now
            updated.append(seed["name"])
            continue
        db.add(CustomSkillORM(
            id=uuid.uuid4().hex,
            name=seed["name"],
            description=seed["description"],
            prompt_body=seed["prompt_body"],
            trigger=seed["trigger"],
            enabled=True,
            tags=seed["tags"],
            category=seed["category"],
            priority=seed["priority"],
            builtin=True,
            created_at=now,
            updated_at=now,
        ))
        created.append(seed["name"])

    db.commit()
    return {
        "created": created,
        "updated": updated,
        "skipped": skipped,
        "total": len(SEEDS),
    }
